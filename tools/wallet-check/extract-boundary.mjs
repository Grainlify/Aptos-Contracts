// Slice the wallet boundary out of index.html so tests run against the REAL
// page source rather than a copy that can drift. Same discipline as the
// backend's buildFromDigests: the vectors pin production code or they pin
// nothing.
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(new URL("./index.html", import.meta.url), "utf8");
const body = html.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1];
if (!body) throw new Error("no module script found in index.html");

const START = "const err = (e) => ({";
const END = "// --- 0. discovery";
const a = body.indexOf(START), b = body.indexOf(END);
if (a < 0 || b < 0 || b < a) throw new Error(
  `boundary markers not found (start=${a} end=${b}). If index.html was ` +
  `restructured, fix these markers - do NOT copy the functions into the test.`);

writeFileSync(new URL("./boundary.generated.mjs", import.meta.url),
  `// GENERATED by extract-boundary.mjs from index.html. Do not edit.\n` +
  `import {\n  Aptos, AptosConfig, Network, Hex, MoveVector, Serializer,\n` +
  `  AccountAddress, generateSigningMessageForTransaction,\n` +
  `  Ed25519PublicKey, Ed25519Signature, AnyPublicKey, AnySignature,\n` +
  `  AccountAuthenticatorEd25519, AccountAuthenticatorSingleKey,\n} from "./vendor/ts-sdk.mjs";\n` +
  `const $ = () => { throw new Error("DOM access from a test"); };\n` +
  body.slice(a, b) +
  `\nexport { unwrap, toBytes, bytesOfLength, senderAuthenticator, normaliseChain, walletChain, CHAIN_IDS, serialised };\n` +
  `export function __inject(w, path, account) { W = w; PATH = path; ACCOUNT = account; }\n`);
console.log("boundary.generated.mjs written from index.html");
